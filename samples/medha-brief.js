/**
 * medha-brief.js — a drop-in client for Medha's brief and notification API.
 *
 * Copy this one file into any PWA. No build step, no dependencies, no
 * package to install. It is an ES module:
 *
 *     import { Medha } from "./medha-brief.js";
 *     const medha = new Medha({ port: 8001, appKey: "journal" });
 *
 *     await medha.pair("418902");                 // once, user-driven
 *     await medha.postBrief([
 *       { title: "Standup at 10", text: "platform team" },
 *       { title: "Rent due",      text: "Friday" }
 *     ]);
 *     await medha.notify({ title: "Build finished", text: "main → green" });
 *
 * ## What this is NOT
 *
 * It is not a way into Samsung's Now Brief. That has no third-party API: its
 * custom cards are authored by the user in Settings and generated by
 * Samsung's own AI, with no field an app can write. This writes to **Medha's**
 * brief — a home-screen widget Medha owns, which several paired apps can
 * write to at once. It is the one digest surface on the device that accepts
 * third-party content.
 *
 * ## Why a shared file rather than per-app code
 *
 * Every integration needs the same four things: a token kept somewhere, an
 * Origin that matches the one it paired from, errors that say which of the
 * five possible causes actually happened, and a rate limit honoured rather
 * than hammered. Re-deriving those per app is how three apps end up with
 * three different wrong answers to "why did this fetch fail".
 *
 * Requires Medha v0.9.2 or newer for the brief endpoints, and v0.9.0 or newer
 * for pairing at all.
 */

const DEFAULT_PORT = 8001;

/** Thrown for every failure, with a machine-readable `code`. */
export class MedhaError extends Error {
  constructor(message, code, status) {
    super(message);
    this.name = "MedhaError";
    this.code = code || "unknown";
    this.status = status || 0;
  }
}

export class Medha {
  /**
   * @param {object} [opts]
   * @param {number} [opts.port=8001]  the port Medha's status card shows.
   * @param {string} [opts.appKey]     storage key suffix. Set this if one
   *   origin hosts more than one app, otherwise they share a token — which
   *   works, but means they also share a brief section and overwrite each
   *   other.
   * @param {Storage|null} [opts.storage=localStorage] where the token lives.
   *   Pass null to keep it in memory only.
   */
  constructor(opts = {}) {
    this.port = opts.port || DEFAULT_PORT;
    this.base = `http://127.0.0.1:${this.port}`;
    this._key = `medha.token.${opts.appKey || "default"}`;
    this._memory = null;
    // Captured rather than read each time so `storage: null` is honoured.
    this._storage = opts.storage === undefined ? safeLocalStorage() : opts.storage;
  }

  // ------------------------------------------------------------- token

  /** The stored credential, or null. */
  get session() {
    if (this._memory) return this._memory;
    if (!this._storage) return null;
    try {
      const raw = this._storage.getItem(this._key);
      return raw ? JSON.parse(raw) : null;
    } catch (_) {
      // Private mode, blocked site data, or a corrupt value. Not fatal:
      // the app just behaves as unpaired.
      return null;
    }
  }

  get paired() {
    return !!(this.session && this.session.token);
  }

  _remember(session) {
    this._memory = session;
    if (!this._storage) return;
    try {
      this._storage.setItem(this._key, JSON.stringify(session));
    } catch (_) {
      /* memory-only for this session; nothing else to do */
    }
  }

  /** Forgets the token. The grant still exists in Medha until revoked. */
  forget() {
    this._memory = null;
    if (!this._storage) return;
    try {
      this._storage.removeItem(this._key);
    } catch (_) {}
  }

  // ------------------------------------------------------------ pairing

  /**
   * Is Medha running? Needs no token, so it is safe to call before pairing
   * and is the right thing to show a "not running" banner from.
   *
   * Note `modelLoaded` is about inference. The brief and notifications work
   * with no model loaded at all — only `/generate` and friends need one.
   */
  async health() {
    const r = await fetch(`${this.base}/health`).catch((e) => {
      throw new MedhaError(explain(e), "unreachable");
    });
    if (!r.ok) throw new MedhaError(`HTTP ${r.status}`, "unreachable", r.status);
    return r.json();
  }

  /**
   * Exchanges a six-digit code for a token.
   *
   * The user gets the code from Medha: drawer → **Pair a web app** → tick
   * **Post notifications** → Create. It lives five minutes, works once, and
   * five wrong guesses destroy it.
   *
   * No Authorization header on this one: obtaining a token is the point.
   */
  async pair(code) {
    const digits = String(code).replace(/\D/g, "");
    if (digits.length !== 6) {
      throw new MedhaError("a pairing code is six digits", "bad_code");
    }
    const body = await this._json("POST", "/pair", { code: digits }, { auth: false });
    this._remember({
      token: body.token,
      clientId: body.clientId,
      namespace: body.namespace,
      origin: body.origin,
      capabilities: body.capabilities || []
    });
    return this.session;
  }

  // -------------------------------------------------------------- brief

  /**
   * Replaces this app's section of the brief.
   *
   * Replace, not append: you are stating your whole current contribution.
   * Other apps' sections are untouched. An empty array withdraws yours.
   *
   * @param {{title: string, text?: string}[]} items  at most 5.
   * @param {object} [opts]
   * @param {number} [opts.ttlSeconds] 60..604800, default 24h. Clamped
   *   server-side, so a long value is capped rather than rejected.
   * @returns {Promise<{items:number, pageRows:number, maxRows:number}>}
   *   `items` is what was KEPT, which can be fewer than you sent.
   */
  async postBrief(items, opts = {}) {
    const payload = { items: normaliseItems(items) };
    if (opts.ttlSeconds != null) payload.ttlSeconds = Math.round(opts.ttlSeconds);
    return this._json("PUT", "/widget/content", payload);
  }

  /** This app's section, with ages resolved. Admin tokens see every app's. */
  async readBrief() {
    return this._json("GET", "/widget/content");
  }

  /** Withdraws this app's section. */
  async clearBrief() {
    return this._json("DELETE", "/widget/content");
  }

  // ------------------------------------------------------- notifications

  /**
   * Posts a notification to the shade.
   *
   * `ongoing` with progress is what may be promoted to the One UI 8 Now Bar.
   * Ask {@link capabilities} what this device can do rather than branching
   * on user-agent or OS version.
   *
   * A resolved promise with `posted: false` is not an error: Medha made the
   * call and Android refused it, which on API 33+ means the user has not
   * granted **Medha** the notification permission. Your own app's permission
   * is irrelevant — Medha posts it, not you.
   */
  async notify(req) {
    if (!req || !req.title) throw new MedhaError("title is required", "bad_request");
    return this._json("POST", "/notify", {
      id: req.id || "default",
      title: String(req.title).slice(0, 200),
      text: String(req.text || "").slice(0, 2000),
      ongoing: !!req.ongoing,
      progressCurrent: req.progressCurrent != null ? req.progressCurrent : -1,
      progressMax: req.progressMax != null ? req.progressMax : -1,
      silent: req.silent !== false
    });
  }

  /** Cancels a notification this app posted. Ids are namespaced per client. */
  async cancelNotification(id = "default") {
    return this._json("DELETE", `/notify/${encodeURIComponent(id)}`);
  }

  /** What this device actually supports. `nowBrief` is always false. */
  async capabilities() {
    return this._json("GET", "/notify/capabilities");
  }

  // ------------------------------------------------------------ internals

  async _json(method, path, body, opts = {}) {
    const headers = {};
    if (body !== undefined) headers["Content-Type"] = "application/json";

    if (opts.auth !== false) {
      const s = this.session;
      if (!s || !s.token) {
        throw new MedhaError(
          "not paired — open Medha, tap 'Pair a web app', and call pair(code)",
          "not_paired"
        );
      }
      headers["Authorization"] = `Bearer ${s.token}`;
    }

    let r;
    try {
      r = await fetch(this.base + path, {
        method,
        headers,
        body: body === undefined ? undefined : JSON.stringify(body)
      });
    } catch (e) {
      throw new MedhaError(explain(e), "unreachable");
    }

    let parsed = null;
    try {
      parsed = await r.json();
    } catch (_) {
      /* some responses legitimately have no body */
    }

    if (!r.ok) {
      const code = (parsed && parsed.code) || `http_${r.status}`;
      let msg = (parsed && parsed.error) || `HTTP ${r.status}`;
      if (r.status === 429) {
        const retry = r.headers.get("Retry-After");
        msg += retry ? ` (retry in ${retry}s)` : "";
      }
      if (code === "origin_mismatch") {
        msg += " — this token was paired from a different origin; pair again";
      }
      if (code === "forbidden") {
        msg += " — pair again and tick 'Post notifications'";
      }
      throw new MedhaError(msg, code, r.status);
    }
    return parsed;
  }
}

// --------------------------------------------------------------- helpers

function normaliseItems(items) {
  if (!Array.isArray(items)) throw new MedhaError("items must be an array", "bad_request");
  return items
    .filter((i) => i && i.title && String(i.title).trim())
    .slice(0, 5) // the server caps at 5 per client; fail here, visibly
    .map((i) => ({
      title: String(i.title).trim().slice(0, 80),
      text: String(i.text || "").trim().slice(0, 200)
    }));
}

/**
 * A bare "Failed to fetch" covers at least five unrelated causes here, and
 * sending someone to a phone's devtools is not a plan.
 */
function explain(err) {
  const msg = String((err && err.message) || err);
  if (/Failed to fetch|NetworkError|Load failed/i.test(msg)) {
    return [
      "Could not reach Medha.",
      "• Is Medha running with the server started?",
      "• Is the port right? Medha's status card shows it.",
      "• A file:// page cannot pair — serve this over http(s).",
      "• Chrome blocks a public page calling a private address unless Medha",
      "  answers the preflight; it does from v0.9.0, so an older build fails here.",
      "• If you cleared site data, the token is gone — pair again."
    ].join("\n");
  }
  return msg;
}

function safeLocalStorage() {
  // Touching localStorage can throw outright in a private window or with
  // site data blocked, so this is probed rather than assumed.
  try {
    const k = "__medha_probe__";
    localStorage.setItem(k, "1");
    localStorage.removeItem(k);
    return localStorage;
  } catch (_) {
    return null;
  }
}
