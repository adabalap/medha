#!/usr/bin/env python3
"""
Writes tools/manifest.txt: every source file this release actually contains.

WHY

Medha ships as a zip of its tree. Extracting one over an existing checkout
adds and overwrites but NEVER deletes, so every file ever removed survives
in the consumer's repo forever and then breaks the build from behind.

tools/removed.txt was the first answer: a hand-maintained list of deletions.
It works, but only for deletions somebody remembered to list, and only from
v0.13.0 onward. It did not catch connectors/SmsConnector.kt, removed back in
v0.9.0 — which sat in a consumer repo for nine releases and only surfaced
when a checker was fixed enough to read it properly.

A list of what SHOULD exist does not have that gap. Anything on disk and not
in the manifest is an orphan, whenever it was orphaned and whether or not
anyone wrote it down.

Run from the project root before packaging a release:

    python3 tools/make_manifest.py
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "tools" / "manifest.txt"

# Only the directories a release actually owns. A consumer's build outputs,
# caches and local scratch files are theirs, not ours, and listing them as
# orphans would make the check noise that people learn to ignore.
TRACKED = ("app/src", "tools", "docs", "samples", ".github")

IGNORE_PARTS = {"build", "node_modules", ".git", "__pycache__", ".gradle", ".idea"}
IGNORE_SUFFIX = {".jar", ".apk", ".class", ".pyc", ".keystore", ".log"}


def tracked_files():
    out = []
    for top in TRACKED:
        base = ROOT / top
        if not base.exists():
            continue
        for p in base.rglob("*"):
            if not p.is_file():
                continue
            rel = p.relative_to(ROOT)
            if IGNORE_PARTS & set(rel.parts):
                continue
            if p.suffix in IGNORE_SUFFIX:
                continue
            out.append(rel.as_posix())
    return sorted(out)


def main():
    files = tracked_files()
    MANIFEST.write_text(
        "# Every source file this release contains, one per line.\n"
        "# Generated by tools/make_manifest.py; checked by tools/check_stale.py.\n"
        "#\n"
        "# A file on disk under app/src, tools, docs, samples or .github that is\n"
        "# NOT listed here is left over from an older release: a zip extracted\n"
        "# over a checkout adds and overwrites but never deletes.\n"
        + "\n".join(files)
        + "\n"
    )
    print(f"manifest: {len(files)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
