package com.adabala.medha.notify

import android.app.Notification
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.content.Context
import android.content.Intent
import android.os.Build
import com.adabala.medha.diag.Diagnostics
import androidx.core.app.NotificationCompat
import androidx.core.app.NotificationManagerCompat
import com.adabala.medha.MainActivity
import com.adabala.medha.R

/**
 * One notification API for PWAs, with three back-ends that degrade by device.
 *
 * ## The surfaces, and which are actually reachable
 *
 * | Surface | Third-party access |
 * |---|---|
 * | **Now Brief** (Samsung's AI daily digest) | **None.** No public API |
 * | **Now Bar** (lock-screen pill) | Yes, One UI 8+ via Android 16 Live Updates |
 * | Standard notification | Yes, everywhere |
 * | Home-screen widget | Yes, if the widget belongs to Medha |
 *
 * Now Brief cannot be targeted and nothing here pretends otherwise. The Now Bar
 * is reachable because One UI 8 adopted Android 16's Live Updates API, which
 * promotes an ongoing notification into the pill. It is designed for *ongoing
 * activities with progress*, not arbitrary cards, so a request without progress
 * simply posts as a normal notification.
 *
 * Clients call [capabilities] first and get a truthful answer for this device
 * rather than branching on OS version themselves.
 */
class NotificationHub(private val appContext: Context) {

    data class Request(
        val id: String,
        val title: String,
        val text: String,
        val ongoing: Boolean = false,
        val progressCurrent: Int = -1,
        val progressMax: Int = -1,
        val silent: Boolean = true,
        val clientId: String = "unknown",
        /**
         * Where tapping the notification should go. http(s) only, already
         * validated by the caller against [BriefJson.isSafeLink].
         *
         * Null keeps the old behaviour: the tap opens Medha. That was the
         * only behaviour until v0.12.1, and a client that wanted the user
         * taken somewhere had to put a URL in [text] — where Android does
         * not linkify it, so it was dead characters on the screen.
         */
        val link: String? = null
    )

    private val manager get() = NotificationManagerCompat.from(appContext)

    /**
     * Called after any write to the brief.
     *
     * Set by InferenceService to [BriefRotator.onBriefChanged], so a brief
     * that has just grown past one page starts rotating immediately rather
     * than at the next service start, and one that has shrunk back stops.
     *
     * A plain nullable hook rather than the rotator as a constructor
     * dependency: BriefActivity builds its own hub for a read-only glance and
     * has no rotator to give it, and a hub that could not be built without
     * one would force a singleton nobody else needs.
     */
    @Volatile var onBriefChanged: (() -> Unit)? = null

    fun capabilities(): Map<String, Any> = mapOf(
        "sdk" to Build.VERSION.SDK_INT,
        // Live Updates landed in Android 16 (API 36). Below that, an ongoing
        // notification still posts, it just never reaches the Now Bar.
        "liveUpdates" to (Build.VERSION.SDK_INT >= 36),
        "nowBarLikely" to (Build.VERSION.SDK_INT >= 36 &&
            Build.MANUFACTURER.equals("samsung", ignoreCase = true)),
        "notifications" to areNotificationsEnabled(),
        "widget" to true,
        // Always false, and it says why. An integrator who reads `false` with
        // no explanation goes looking for the flag they got wrong; this tells
        // them there is nothing to get right. Samsung's Now Brief has no
        // public API: the custom cards added in One UI 9 are authored by the
        // user in Settings and generated by Samsung's own AI, with no field
        // an app can write. Medha's own brief is the writable equivalent --
        // see /widget/content and docs/NOTIFICATIONS.md.
        "nowBrief" to false,
        "nowBriefReason" to "no public API; use /widget/content for Medha's own brief",
        "brief" to true,
        "briefRows" to BriefPolicy.MAX_ROWS,
        "briefTtlSecondsDefault" to (BriefPolicy.DEFAULT_TTL_MS / 1000).toInt()
    )

    fun areNotificationsEnabled(): Boolean =
        runCatching { manager.areNotificationsEnabled() }.getOrDefault(false)

    fun post(req: Request): Boolean {
        ensureChannel()
        val key = stableId(req.clientId, req.id)

        // Where a tap goes. A safe link takes the user there; otherwise
        // Medha's own screen, which is what every notification did before
        // v0.12.1.
        //
        // CATEGORY_BROWSABLE is added for the same reason BriefActivity
        // adds it: both tap paths then resolve by one rule, so an app
        // wanting to claim its own links registers one filter shape rather
        // than discovering that the two surfaces behave differently. The
        // cost, which is worth stating plainly in the docs: a filter that
        // omits BROWSABLE will not match, and the link quietly goes to the
        // browser instead.
        val target = req.link
            ?.let { Intent(Intent.ACTION_VIEW, android.net.Uri.parse(it))
                .addCategory(Intent.CATEGORY_BROWSABLE) }
            ?: Intent(appContext, MainActivity::class.java)

        val open = PendingIntent.getActivity(
            appContext, key, target,
            PendingIntent.FLAG_UPDATE_CURRENT or
                (if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) PendingIntent.FLAG_IMMUTABLE else 0)
        )

        val b = NotificationCompat.Builder(appContext, CHANNEL_ID)
            .setSmallIcon(R.drawable.ic_stat_medha)
            .setContentTitle(req.title)
            .setContentText(req.text)
            .setStyle(NotificationCompat.BigTextStyle().bigText(req.text))
            .setContentIntent(open)
            .setOnlyAlertOnce(true)
            .setSilent(req.silent)
            .setOngoing(req.ongoing)
            .setCategory(if (req.ongoing) NotificationCompat.CATEGORY_PROGRESS else NotificationCompat.CATEGORY_STATUS)

        if (req.progressMax > 0) {
            b.setProgress(req.progressMax, req.progressCurrent.coerceIn(0, req.progressMax), false)
        }

        val n = b.build()

        // Ask the platform to promote this into the status-bar chip / Now Bar.
        // Set reflectively: FLAG_PROMOTED_ONGOING only exists on API 36+, and a
        // direct reference would not compile against compileSdk 34. A device
        // that does not know the flag simply ignores the bit.
        if (req.ongoing && Build.VERSION.SDK_INT >= 36) {
            runCatching {
                val f = Notification::class.java.getField("FLAG_PROMOTED_ONGOING")
                n.flags = n.flags or f.getInt(null)
            }.onFailure { Diagnostics.d(TAG, "promoted-ongoing flag unavailable") }
        }

        return runCatching {
            manager.notify(key, n)
            true
        }.onFailure { Diagnostics.w(TAG, "notify failed (permission?)", it) }.getOrDefault(false)
    }

    fun cancel(clientId: String, id: String) {
        runCatching { manager.cancel(stableId(clientId, id)) }
    }

    /**
     * Namespaced so two clients using id "progress" cannot overwrite each
     * other's notification.
     */
    private fun stableId(clientId: String, id: String): Int =
        ("$clientId/$id".hashCode() and 0x7FFFFFFF) or 1

    @Volatile private var channelReady = false

    /**
     * Creates the channel once per process.
     *
     * createNotificationChannel is idempotent, but it is a binder call into
     * system_server, and this used to run on every single POST /notify. With
     * the endpoint now rate-limited to tens of calls a minute that is not a
     * crisis, but paying for an IPC to re-create a channel that already
     * exists is pure overhead on the one request path that is supposed to be
     * fast.
     *
     * The flag is per-process, so a user who deletes the channel in system
     * settings gets it back when Medha's process next starts rather than on
     * the next post. That is the correct trade: a channel the user actively
     * deleted should not silently reappear mid-session.
     */
    private fun ensureChannel() {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return
        if (channelReady) return
        synchronized(this) {
            if (channelReady) return
            val mgr = appContext.getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager
            mgr.createNotificationChannel(
                NotificationChannel(CHANNEL_ID, "Medha apps", NotificationManager.IMPORTANCE_DEFAULT)
                    .apply { description = "Notifications posted by apps using Medha" }
            )
            channelReady = true
        }
    }

    // ------------------------------ widget ------------------------------

    /**
     * Content is stored rather than pushed: the widget host may not be alive
     * when a client posts, and AppWidgetManager updates are lossy if the
     * provider has not been placed on a home screen yet.
     *
     * This is the thin JSON layer. Every rule — merge, expiry, ordering,
     * bounds — lives in [BriefPolicy], which is pure Kotlin and therefore
     * actually tested. This function only translates.
     *
     * Serialises on [briefLock] because read-modify-write on one
     * SharedPreferences key is not atomic, and two clients posting at the
     * same moment would otherwise drop one of the two sections — the very
     * bug the per-client split exists to prevent, reintroduced as a race.
     */
    fun setBrief(
        clientId: String,
        items: List<BriefPolicy.Item>,
        ttlMs: Long = BriefPolicy.DEFAULT_TTL_MS
    ): Int = synchronized(briefLock) {
        val merged = BriefPolicy.put(
            existing = readSections(),
            clientId = clientId,
            items = items,
            now = System.currentTimeMillis(),
            ttlMs = ttlMs
        )
        writeSections(merged)
        MedhaWidgetProvider.refresh(appContext)
        onBriefChanged?.invoke()
        return merged.firstOrNull { it.clientId == clientId }?.items?.size ?: 0
    }

    /**
     * Empties the brief entirely.
     *
     * Only reached from [com.adabala.medha.BriefActivity], never from the
     * HTTP API: one client being able to wipe another's section is exactly
     * the last-writer-wins behaviour the per-client split removed. The user
     * owning their own home screen is a different thing.
     */
    fun clearAllBrief() = synchronized(briefLock) {
        writeSections(emptyList())
        MedhaWidgetProvider.refresh(appContext)
        onBriefChanged?.invoke()
    }

    /** Withdraws [clientId]'s section. Returns true if there was one. */
    fun clearBrief(clientId: String): Boolean = synchronized(briefLock) {
        val before = readSections()
        val had = before.any { it.clientId == clientId }
        writeSections(BriefPolicy.remove(before, clientId, System.currentTimeMillis()))
        MedhaWidgetProvider.refresh(appContext)
        onBriefChanged?.invoke()
        return had
    }

    /**
     * Live sections, newest first, expired ones already dropped.
     *
     * Pruning on read is the only cleanup there is, deliberately: a timer or
     * a WorkManager job to delete text nobody is looking at would be a wakeup
     * and a reason for the OS to keep Medha alive, for no benefit.
     */
    fun brief(): List<BriefPolicy.Section> =
        BriefPolicy.prune(readSections(), System.currentTimeMillis())

    // One reader and one writer of the on-disk shape, both delegating to
    // BriefJson so the format -- including the v0.9.0 migration -- lives in a
    // file that can be compiled and executed without the Android SDK.
    internal fun readSections(): List<BriefPolicy.Section> {
        val raw = appContext.getSharedPreferences(WIDGET_PREFS, Context.MODE_PRIVATE)
            .getString(WIDGET_KEY, null) ?: return emptyList()
        return BriefJson.parse(raw, System.currentTimeMillis())
    }

    private fun writeSections(sections: List<BriefPolicy.Section>) {
        appContext.getSharedPreferences(WIDGET_PREFS, Context.MODE_PRIVATE)
            .edit()
            .putString(WIDGET_KEY, BriefJson.encode(sections))
            .apply()
    }

    companion object {
        private const val TAG = "NotificationHub"
        private const val CHANNEL_ID = "medha_apps"
        const val WIDGET_PREFS = "medha_widget"
        const val WIDGET_KEY = "content"

        /**
         * Guards read-modify-write on the single brief key. Static because
         * the widget provider is a BroadcastReceiver and gets its own
         * instance, so a per-object lock would guard nothing.
         */
        private val briefLock = Any()
    }
}
